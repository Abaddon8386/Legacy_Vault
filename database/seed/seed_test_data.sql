
/*
 LegacyVault — PS-73 local/dev test seed (SQL Server)
 Run after Flyway migrations on a disposable/local development database only.
 This script does not delete data and is designed to be re-runnable for its labeled demo records.
 IMPORTANT: replace the BCrypt placeholder with a hash generated by the application's BCryptPasswordEncoder.
 The encrypted bytes below are dummy placeholders, not real ciphertext and must never be treated as valid encrypted documents.
*/
USE [LegacyVault];
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

-- Fail fast if the old schema still has the removed share_ratio column as NOT NULL.
IF EXISTS (
    SELECT 1 FROM sys.columns c
    JOIN sys.tables t ON t.object_id = c.object_id
    JOIN sys.schemas s ON s.schema_id = t.schema_id
    WHERE s.name = 'dbo' AND t.name = 'asset_allocations'
      AND c.name = 'share_ratio' AND c.is_nullable = 0
)
    THROW 51020, 'Schema mismatch: dbo.asset_allocations still requires share_ratio. Do not run this seed until schema is migrated.', 1;
GO

BEGIN TRY
    BEGIN TRANSACTION;

    DECLARE @OwnerUserId BIGINT, @AdminUserId BIGINT, @VerifierUserId BIGINT, @ExecutorUserId BIGINT;
    DECLARE @BeneficiaryUser1Id BIGINT, @BeneficiaryUser2Id BIGINT;
    DECLARE @OwnerRoleId BIGINT, @AdminRoleId BIGINT, @VerifierRoleId BIGINT, @ExecutorRoleId BIGINT, @BeneficiaryRoleId BIGINT;
    DECLARE @VaultId BIGINT, @AssetDocId BIGINT, @AssetCredId BIGINT;
    DECLARE @VersionId BIGINT, @LegalDocumentId BIGINT, @Beneficiary1Id BIGINT, @Beneficiary2Id BIGINT;
    DECLARE @DmsId BIGINT;
    DECLARE @DemoBcryptHash NVARCHAR(255) = N'REPLACE_WITH_BCRYPT_HASH';
    DECLARE @DemoFileBytes VARBINARY(MAX) = 0x4C65676163795661756C7420544553542046494C45; -- 'LegacyVault TEST FILE'; dummy only
    DECLARE @DemoSha256 CHAR(64) = CONVERT(CHAR(64), HASHBYTES('SHA2_256', 0x4C65676163795661756C7420544553542046494C45), 2);

    -- V1 inserts the five role rows. Confirm required roles exist before seeding.
    SELECT @OwnerRoleId = role_id FROM dbo.roles WHERE role_code = 'ROLE_VAULT_OWNER';
    SELECT @AdminRoleId = role_id FROM dbo.roles WHERE role_code = 'ROLE_ADMIN';
    SELECT @VerifierRoleId = role_id FROM dbo.roles WHERE role_code = 'ROLE_LEGAL_VERIFIER';
    SELECT @ExecutorRoleId = role_id FROM dbo.roles WHERE role_code = 'ROLE_STAFF_EXECUTOR';
    SELECT @BeneficiaryRoleId = role_id FROM dbo.roles WHERE role_code = 'ROLE_BENEFICIARY';
    IF @OwnerRoleId IS NULL OR @AdminRoleId IS NULL OR @VerifierRoleId IS NULL
       OR @ExecutorRoleId IS NULL OR @BeneficiaryRoleId IS NULL
        THROW 51021, 'One or more required roles are missing. Confirm Flyway V1 completed successfully.', 1;

    SELECT @OwnerUserId = user_id FROM dbo.users WHERE email = 'seed.owner@legacyvault.local';
    IF @OwnerUserId IS NULL
    BEGIN
        IF @DemoBcryptHash = N'REPLACE_WITH_BCRYPT_HASH'
            THROW 51022, 'Replace @DemoBcryptHash with a generated BCrypt hash before running the seed.', 1;
        INSERT dbo.users(full_name,email,phone_number,password_hash,status,email_verified_at)
        VALUES(N'[TEST] LegacyVault Demo Owner','seed.owner@legacyvault.local','0900000000',@DemoBcryptHash,'ACTIVE',SYSUTCDATETIME());
        SET @OwnerUserId = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;

    IF NOT EXISTS (SELECT 1 FROM dbo.user_roles WHERE user_id=@OwnerUserId AND role_id=@OwnerRoleId)
        INSERT dbo.user_roles(user_id,role_id,assigned_by_user_id) VALUES(@OwnerUserId,@OwnerRoleId,NULL);

    -- Create separate demo accounts for RBAC testing. Existing accounts are never overwritten.
    -- All demo accounts use the same BCrypt hash placeholder; replace it with a valid test hash before first run.
    SELECT @AdminUserId = user_id FROM dbo.users WHERE email='seed.admin@legacyvault.local';
    IF @AdminUserId IS NULL
    BEGIN
        IF @DemoBcryptHash = N'REPLACE_WITH_BCRYPT_HASH'
            THROW 51022, 'Replace @DemoBcryptHash with a generated BCrypt hash before creating demo accounts.', 1;
        INSERT dbo.users(full_name,email,phone_number,password_hash,status,email_verified_at)
        VALUES(N'[TEST] LegacyVault Demo Admin','seed.admin@legacyvault.local','0900000001',@DemoBcryptHash,'ACTIVE',SYSUTCDATETIME());
        SET @AdminUserId = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;
    IF NOT EXISTS (SELECT 1 FROM dbo.user_roles WHERE user_id=@AdminUserId AND role_id=@AdminRoleId)
        INSERT dbo.user_roles(user_id,role_id,assigned_by_user_id) VALUES(@AdminUserId,@AdminRoleId,NULL);

    SELECT @VerifierUserId = user_id FROM dbo.users WHERE email='seed.verifier@legacyvault.local';
    IF @VerifierUserId IS NULL
    BEGIN
        IF @DemoBcryptHash = N'REPLACE_WITH_BCRYPT_HASH'
            THROW 51022, 'Replace @DemoBcryptHash with a generated BCrypt hash before creating demo accounts.', 1;
        INSERT dbo.users(full_name,email,phone_number,password_hash,status,email_verified_at)
        VALUES(N'[TEST] LegacyVault Demo Legal Verifier','seed.verifier@legacyvault.local','0900000002',@DemoBcryptHash,'ACTIVE',SYSUTCDATETIME());
        SET @VerifierUserId = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;
    IF NOT EXISTS (SELECT 1 FROM dbo.user_roles WHERE user_id=@VerifierUserId AND role_id=@VerifierRoleId)
        INSERT dbo.user_roles(user_id,role_id,assigned_by_user_id) VALUES(@VerifierUserId,@VerifierRoleId,NULL);

    SELECT @ExecutorUserId = user_id FROM dbo.users WHERE email='seed.executor@legacyvault.local';
    IF @ExecutorUserId IS NULL
    BEGIN
        IF @DemoBcryptHash = N'REPLACE_WITH_BCRYPT_HASH'
            THROW 51022, 'Replace @DemoBcryptHash with a generated BCrypt hash before creating demo accounts.', 1;
        INSERT dbo.users(full_name,email,phone_number,password_hash,status,email_verified_at)
        VALUES(N'[TEST] LegacyVault Demo Staff Executor','seed.executor@legacyvault.local','0900000003',@DemoBcryptHash,'ACTIVE',SYSUTCDATETIME());
        SET @ExecutorUserId = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;
    IF NOT EXISTS (SELECT 1 FROM dbo.user_roles WHERE user_id=@ExecutorUserId AND role_id=@ExecutorRoleId)
        INSERT dbo.user_roles(user_id,role_id,assigned_by_user_id) VALUES(@ExecutorUserId,@ExecutorRoleId,NULL);

    SELECT @BeneficiaryUser1Id = user_id FROM dbo.users WHERE email='seed.beneficiary1@legacyvault.local';
    IF @BeneficiaryUser1Id IS NULL
    BEGIN
        IF @DemoBcryptHash = N'REPLACE_WITH_BCRYPT_HASH'
            THROW 51022, 'Replace @DemoBcryptHash with a generated BCrypt hash before creating demo accounts.', 1;
        INSERT dbo.users(full_name,email,phone_number,password_hash,status,email_verified_at)
        VALUES(N'[TEST] LegacyVault Demo Beneficiary One','seed.beneficiary1@legacyvault.local','0900000004',@DemoBcryptHash,'ACTIVE',SYSUTCDATETIME());
        SET @BeneficiaryUser1Id = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;
    IF NOT EXISTS (SELECT 1 FROM dbo.user_roles WHERE user_id=@BeneficiaryUser1Id AND role_id=@BeneficiaryRoleId)
        INSERT dbo.user_roles(user_id,role_id,assigned_by_user_id) VALUES(@BeneficiaryUser1Id,@BeneficiaryRoleId,NULL);

    SELECT @BeneficiaryUser2Id = user_id FROM dbo.users WHERE email='seed.beneficiary2@legacyvault.local';
    IF @BeneficiaryUser2Id IS NULL
    BEGIN
        IF @DemoBcryptHash = N'REPLACE_WITH_BCRYPT_HASH'
            THROW 51022, 'Replace @DemoBcryptHash with a generated BCrypt hash before creating demo accounts.', 1;
        INSERT dbo.users(full_name,email,phone_number,password_hash,status,email_verified_at)
        VALUES(N'[TEST] LegacyVault Demo Beneficiary Two','seed.beneficiary2@legacyvault.local','0900000005',@DemoBcryptHash,'ACTIVE',SYSUTCDATETIME());
        SET @BeneficiaryUser2Id = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;
    IF NOT EXISTS (SELECT 1 FROM dbo.user_roles WHERE user_id=@BeneficiaryUser2Id AND role_id=@BeneficiaryRoleId)
        INSERT dbo.user_roles(user_id,role_id,assigned_by_user_id) VALUES(@BeneficiaryUser2Id,@BeneficiaryRoleId,NULL);

    SELECT @VaultId = vault_id FROM dbo.vaults WHERE owner_user_id=@OwnerUserId;
    IF @VaultId IS NULL
    BEGIN
        INSERT dbo.vaults(owner_user_id,vault_name,description,status)
        VALUES(@OwnerUserId,N'[TEST] LegacyVault Demo Vault',N'Dữ liệu giả lập PS-73; không chứa tài sản thật.','ACTIVE');
        SET @VaultId = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;

    SELECT @AssetDocId = asset_id FROM dbo.assets WHERE vault_id=@VaultId AND title=N'[TEST] Digitized Will';
    IF @AssetDocId IS NULL
    BEGIN
        INSERT dbo.assets(vault_id,asset_type,title,description,encrypted_payload,encryption_iv,encryption_key_version,status)
        VALUES(@VaultId,N'DOCUMENT',N'[TEST] Digitized Will',N'Tài liệu giả lập; file version nằm ở asset_versions.',NULL,NULL,NULL,N'ACTIVE');
        SET @AssetDocId = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;

    SELECT @VersionId = asset_version_id FROM dbo.asset_versions WHERE asset_id=@AssetDocId AND version_no=1;
    IF @VersionId IS NULL
    BEGIN
        INSERT dbo.asset_versions(asset_id,version_no,original_file_name,content_type,file_size_bytes,sha256_hash,
            encrypted_file_content,encryption_iv,encryption_key_version,upload_status,uploaded_by_user_id)
        VALUES(@AssetDocId,1,N'demo-will.txt',N'text/plain',DATALENGTH(@DemoFileBytes),@DemoSha256,
            @DemoFileBytes,0x000102030405060708090A0B,N'TEST-ONLY',N'UPLOADED',@OwnerUserId);
        SET @VersionId = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;

    SELECT @LegalDocumentId = legal_document_id FROM dbo.legal_documents WHERE asset_id=@AssetDocId;
    IF @LegalDocumentId IS NULL
    BEGIN
        INSERT dbo.legal_documents(asset_id,document_type,verification_status,submitted_at)
        VALUES(@AssetDocId,N'WILL',N'PENDING_VERIFICATION',NULL);
        SET @LegalDocumentId = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;

    -- Add one pending verification history row if no seed row exists. Upload does not mean legal approval.
    IF NOT EXISTS (SELECT 1 FROM dbo.legal_verifications WHERE legal_document_id=@LegalDocumentId AND remarks=N'[TEST] Seed pending verification')
        INSERT dbo.legal_verifications(legal_document_id,asset_version_id,verifier_user_id,result,remarks,requested_at,decided_at)
        VALUES(@LegalDocumentId,@VersionId,NULL,N'PENDING',N'[TEST] Seed pending verification',SYSUTCDATETIME(),NULL);

    SELECT @AssetCredId = asset_id FROM dbo.assets WHERE vault_id=@VaultId AND title=N'[TEST] Digital Credential';
    IF @AssetCredId IS NULL
    BEGIN
        INSERT dbo.assets(vault_id,asset_type,title,description,encrypted_payload,encryption_iv,encryption_key_version,status)
        VALUES(@VaultId,N'CREDENTIAL',N'[TEST] Digital Credential',N'Credential giả lập, không dùng tài khoản thật.',
            0x544553545F43524544454E5449414C,0x0C0D0E0F1011121314151617,N'TEST-ONLY',N'ACTIVE');
        SET @AssetCredId = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;

    SELECT @Beneficiary1Id = beneficiary_id FROM dbo.beneficiaries WHERE vault_id=@VaultId AND email='seed.beneficiary1@legacyvault.local';
    IF @Beneficiary1Id IS NULL
    BEGIN
        INSERT dbo.beneficiaries(vault_id,linked_user_id,full_name,email,phone_number,designation_status,id_verification_status,account_status)
        VALUES(@VaultId,@BeneficiaryUser1Id,N'[TEST] Beneficiary One','seed.beneficiary1@legacyvault.local','0910000001',N'DESIGNATED',N'NOT_VERIFIED',N'ACCOUNT_CREATED');
        SET @Beneficiary1Id = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;
    UPDATE dbo.beneficiaries SET linked_user_id=@BeneficiaryUser1Id, account_status=N'ACCOUNT_CREATED'
    WHERE beneficiary_id=@Beneficiary1Id AND linked_user_id IS NULL;

    SELECT @Beneficiary2Id = beneficiary_id FROM dbo.beneficiaries WHERE vault_id=@VaultId AND email='seed.beneficiary2@legacyvault.local';
    IF @Beneficiary2Id IS NULL
    BEGIN
        INSERT dbo.beneficiaries(vault_id,linked_user_id,full_name,email,phone_number,designation_status,id_verification_status,account_status)
        VALUES(@VaultId,@BeneficiaryUser2Id,N'[TEST] Beneficiary Two','seed.beneficiary2@legacyvault.local','0910000002',N'DESIGNATED',N'NOT_VERIFIED',N'ACCOUNT_CREATED');
        SET @Beneficiary2Id = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;
    UPDATE dbo.beneficiaries SET linked_user_id=@BeneficiaryUser2Id, account_status=N'ACCOUNT_CREATED'
    WHERE beneficiary_id=@Beneficiary2Id AND linked_user_id IS NULL;

    IF NOT EXISTS(SELECT 1 FROM dbo.asset_allocations WHERE asset_id=@AssetDocId AND beneficiary_id=@Beneficiary1Id)
        INSERT dbo.asset_allocations(asset_id,beneficiary_id,allocation_description,version_no,status)
        VALUES(@AssetDocId,@Beneficiary1Id,N'[TEST] Allocation to Beneficiary One',1,N'DRAFT');
    IF NOT EXISTS(SELECT 1 FROM dbo.asset_allocations WHERE asset_id=@AssetDocId AND beneficiary_id=@Beneficiary2Id)
        INSERT dbo.asset_allocations(asset_id,beneficiary_id,allocation_description,version_no,status)
        VALUES(@AssetDocId,@Beneficiary2Id,N'[TEST] Allocation to Beneficiary Two',1,N'DRAFT');

    IF NOT EXISTS(SELECT 1 FROM dbo.trustees WHERE vault_id=@VaultId AND status=N'APPOINTED')
        INSERT dbo.trustees(vault_id,full_name,phone_number,email,relationship_to_owner,status)
        VALUES(@VaultId,N'[TEST] Demo Trustee','0920000000','seed.trustee@legacyvault.local',N'Demo relation',N'APPOINTED');

    SELECT @DmsId = dms_id FROM dbo.dms_configs WHERE owner_user_id=@OwnerUserId;
    IF @DmsId IS NULL
    BEGIN
        INSERT dbo.dms_configs(owner_user_id,check_interval_days,grace_period_days,status,last_check_in_at,next_check_at,triggered_at,grace_period_ends_at)
        VALUES(@OwnerUserId,30,1,N'MONITORING',SYSUTCDATETIME(),DATEADD(DAY,30,SYSUTCDATETIME()),NULL,NULL);
        SET @DmsId = CONVERT(BIGINT,SCOPE_IDENTITY());
    END;

    IF NOT EXISTS(SELECT 1 FROM dbo.vitality_check_logs WHERE dms_id=@DmsId AND event_type=N'TEST_SEED_CREATED')
        INSERT dbo.vitality_check_logs(dms_id,event_type,event_at,channel,details)
        VALUES(@DmsId,N'TEST_SEED_CREATED',SYSUTCDATETIME(),N'SYSTEM',N'[TEST] Demo DMS row created by seed.');

    IF NOT EXISTS(SELECT 1 FROM dbo.audit_logs WHERE action=N'TEST_SEED_CREATED' AND entity_type=N'Vault' AND entity_id=@VaultId)
        INSERT dbo.audit_logs(actor_user_id,vault_id,action,entity_type,entity_id,details)
        VALUES(@OwnerUserId,@VaultId,N'TEST_SEED_CREATED',N'Vault',@VaultId,N'{"source":"seed_test_data","testData":true}');

    COMMIT TRANSACTION;
    SELECT N'SEED_COMPLETED' AS result,
        @OwnerUserId AS owner_user_id, @AdminUserId AS admin_user_id,
        @VerifierUserId AS verifier_user_id, @ExecutorUserId AS executor_user_id,
        @BeneficiaryUser1Id AS beneficiary_user_1_id, @BeneficiaryUser2Id AS beneficiary_user_2_id,
        @VaultId AS vault_id, @AssetDocId AS will_asset_id, @VersionId AS asset_version_id,
        @LegalDocumentId AS legal_document_id, @Beneficiary1Id AS beneficiary_1_id,
        @Beneficiary2Id AS beneficiary_2_id, @DmsId AS dms_id;

    -- Explicit RBAC demo account report.
    SELECT u.email, r.role_code, u.status
    FROM dbo.users u
    JOIN dbo.user_roles ur ON ur.user_id=u.user_id
    JOIN dbo.roles r ON r.role_id=ur.role_id
    WHERE u.email IN (
        'seed.owner@legacyvault.local',
        'seed.admin@legacyvault.local',
        'seed.verifier@legacyvault.local',
        'seed.executor@legacyvault.local',
        'seed.beneficiary1@legacyvault.local',
        'seed.beneficiary2@legacyvault.local'
    )
    ORDER BY u.email, r.role_code;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
GO

-- Post-seed verification (counts are informational, not assertions of expected global totals).
SELECT 'roles' AS table_name, COUNT_BIG(*) AS row_count FROM dbo.roles
UNION ALL SELECT 'users', COUNT_BIG(*) FROM dbo.users
UNION ALL SELECT 'vaults', COUNT_BIG(*) FROM dbo.vaults
UNION ALL SELECT 'assets', COUNT_BIG(*) FROM dbo.assets
UNION ALL SELECT 'asset_versions', COUNT_BIG(*) FROM dbo.asset_versions
UNION ALL SELECT 'legal_documents', COUNT_BIG(*) FROM dbo.legal_documents
UNION ALL SELECT 'legal_verifications', COUNT_BIG(*) FROM dbo.legal_verifications
UNION ALL SELECT 'beneficiaries', COUNT_BIG(*) FROM dbo.beneficiaries
UNION ALL SELECT 'trustees', COUNT_BIG(*) FROM dbo.trustees
UNION ALL SELECT 'asset_allocations', COUNT_BIG(*) FROM dbo.asset_allocations
UNION ALL SELECT 'dms_configs', COUNT_BIG(*) FROM dbo.dms_configs
UNION ALL SELECT 'vitality_check_logs', COUNT_BIG(*) FROM dbo.vitality_check_logs
UNION ALL SELECT 'audit_logs', COUNT_BIG(*) FROM dbo.audit_logs;
GO
